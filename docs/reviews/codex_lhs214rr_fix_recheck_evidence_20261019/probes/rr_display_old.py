"""Compile unchanged old display_fresh bytes with a relocated __file__.

Only adapter: its unrelated K2 check reads old display_source.json (existing
producer fixtures) because those were not regenerated by this display subtask.
All display cases use current pinned source and all outputs use this review.
"""
import hashlib
import json
from pathlib import Path
import sys

review = Path(__file__).resolve().parents[1]
old = review.parent / 'lhs214r_fix_recheck_20261017'
probe = old / 'probes/display_fresh.py'
original = probe.read_bytes()
original_div = Path.__truediv__
def adapted_div(self, other):
    """Keep the original probe's output namespace under rr_display_* only."""
    if str(other).startswith('display_fresh'):
        other = str(other).replace('display_fresh', 'rr_display_old_replay', 1)
    return original_div(self, other)
read_text = Path.read_text
def adapted_read_text(self, *args, **kwargs):
    if self.resolve() == (review/'evidence/display_source.json').resolve():
        return read_text(old/'evidence/display_source.json', *args, **kwargs)
    return read_text(self, *args, **kwargs)
Path.read_text = adapted_read_text
Path.__truediv__ = adapted_div
sys.argv = [str(probe), 'source']
ns = {'__file__': str(review/'probes/display_fresh.py'), '__name__': '__main__'}
try:
    exec(compile(original, str(probe), 'exec'), ns)
finally:
    Path.__truediv__ = original_div
    Path.read_text = read_text
    (review/'evidence/rr_display_old_adapter.json').write_text(json.dumps({
        'original': str(probe), 'sha256': hashlib.sha256(original).hexdigest(),
        'byte_changes': 0, '__file__': ns['__file__'],
        'output_namespace_adapter': 'Path division maps display_fresh* -> rr_display_old_replay*',
        'K2_read_adapter': str(old/'evidence/display_source.json'),
        'K2_scope': 'old fixture only; not display evidence',
        'display_source': str(review/'source')}, indent=2), encoding='utf-8')
