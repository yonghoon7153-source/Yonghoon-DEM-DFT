/** 피팅 파라미터 이름을 사람 말로.
 *
 *  서버가 **아크**에는 이미 이름을 붙인다 (`label_arcs` — 이 셀에서 그 저항이
 *  무엇인지는 셀 구성에 따라 달라서 서버가 정한다).  하지만 아크가 아닌 것
 *  (인덕턴스, CPE 지수, 전송선 안쪽)은 이름이 없어서 표의 '뜻' 칸이 줄줄이
 *  `—` 였다 — 열세 줄 중 두 줄만 채워진 표는 읽는 사람에게 "모르는 것이 열한
 *  개" 로 보인다.
 *
 *  여기 있는 것은 **회로 원소가 무엇인지**이고 셀에 따라 달라지지 않는다.
 *  그래서 화면에 둔다: 서버의 아크 이름이 있으면 그것이 이기고, 없을 때만
 *  이 표가 받는다.
 */

/** 굵게·강조색으로 낼 것인가 — 보고서에 실제로 옮겨 적는 값인가.
 *
 *  저항이다.  전도도·면적저항으로 바로 이어지고 셀끼리 비교하는 수도 이것들
 *  이다.  지수(`_n`)와 축전 크기(`_Q`)는 모양을 정하는 값이지 옮겨 적는 값이
 *  아니고, 인덕턴스는 아예 셀의 것이 아니다.
 */
export function isHeadline(name: string): boolean {
  return isOhmParam(name)
}

/** 이 파라미터의 단위가 **Ω 인가**.
 *
 *  면적으로 나눠도 되는 것과 안 되는 것을 가른다.  Ω 은 나누면 Ω·cm² 이고
 *  그것이 셀끼리 견주는 수다.  나머지는 그렇지 않다: `_Q` 는 S·sⁿ 이라 면적을
 *  **곱해야** 하고, `_n`·`_Wn` 은 무차원이며, `_tau`·`_Wt` 는 초다 — 셋 다
 *  나누면 아무 뜻도 없는 수가 되는데 화면에는 `Ω·cm²` 라고 적힌다 (§0.4).
 *  그래서 이름으로 판정한다: 서버가 스캔의 파라미터에 단위를 실어 보내지
 *  않으므로 (`ScanPoint.values` 는 이름 → 수뿐) 여기가 유일한 근거다.
 *
 *  같은 집합이 '보고서에 옮겨 적는 값'(`isHeadline`)이기도 하다 — 우연이
 *  아니라 같은 이유다: 옮겨 적는 것이 저항이고, 정규화할 수 있는 것도 저항이다.
 */
export function isOhmParam(name: string): boolean {
  if (/^R\d+$/.test(name)) return true
  return /_(Rct|Ri|Re|Wr|R)$/.test(name)
}

const EXACT: Record<string, string> = {
  R0: '직렬 저항 — 전해질과 배선을 합친 실수축 절편',
}

/** 접미사로 읽는다.  `TL1_Rct` 도 `Ws2_R` 도 규칙은 하나다. */
const BY_SUFFIX: [RegExp, string][] = [
  [/^L\d+$/, '배선 인덕턴스 — 케이블·셀 홀더의 것이지 셀이 아닙니다'],
  [/^C\d+$/, '전기용량'],
  [/^R\d+$/, '아크 저항 — 반원의 지름'],
  [/_Rct$/, '전하이동 저항 — 반응이 얼마나 안 일어나는가'],
  [/_Ri$/, '이온이 지나는 길의 저항'],
  [/_Re$/, '전자가 지나는 길의 저항'],
  [/_Q$/, 'CPE 크기 — 축전 용량에 해당 (지수 n 이 1 이면 그대로 F)'],
  [/_n$/, 'CPE 지수 — 1 이면 순수 축전기, 낮을수록 퍼진(불균일한) 계면'],
  [/_Wr$/, '확산 저항 — 확산이 만드는 저주파 꼬리의 크기'],
  [/_Wn$/, '확산 지수 — 0.5 가 교과서 확산, 벗어나면 그만큼 불균일'],
  [/_Wt$/, '확산 시간 — 이온이 확산층을 건너는 데 걸리는 시간'],
  [/_R$/, '확산 저항 — 확산이 만드는 저주파 꼬리의 크기'],
  [/_tau$/, '확산 시간 — 이온이 확산층을 건너는 데 걸리는 시간'],
  [/_T$/, '확산 시간 — 이온이 확산층을 건너는 데 걸리는 시간'],
  [/_P$/, '확산 지수 — 0.5 가 교과서 확산'],
]

/** 이름을 밑첨자로 쪼갠다: `["CPE", "1,Q"]`.
 *
 *  화면이 `CPE1_Q` 라고 적으면 읽는 사람은 그것을 **변수 이름**으로 본다.
 *  논문과 절차서에는 CPE₁,Q 라고 쓰고, 랩에서 주고받는 표(배영진 목록)도
 *  `R2 (ohm)` · `C2 (F)` · `N2` 처럼 번호가 첨자다.  같은 것을 같게 적는다.
 *
 *  규칙은 둘뿐이다: 원소 이름 뒤의 **숫자**와, 밑줄 뒤의 **접미사**가 첨자다.
 *  못 쪼개면 통째로 본체다 — 모르는 이름을 억지로 자르지 않는다.
 */
export function splitSubscript(name: string): [string, string] {
  const match = /^([A-Za-z]+)(\d*)(?:_(.+))?$/.exec(name)
  if (!match) return [name, '']
  const [, base, index, suffix] = match
  const parts = [index, suffix].filter((part) => part)
  return [base ?? name, parts.join(',')]
}

/** 이 파라미터가 무엇인가.  모르면 빈 문자열 — 지어내지 않는다 (§0.4). */
export function paramMeaning(name: string): string {
  const exact = EXACT[name]
  if (exact) return exact
  for (const [pattern, text] of BY_SUFFIX) {
    if (pattern.test(name)) return text
  }
  return ''
}
