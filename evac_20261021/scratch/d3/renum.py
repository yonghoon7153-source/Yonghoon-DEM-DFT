import sys

p = sys.argv[1]
s = open(p, encoding='utf-8').read()
pairs = [
    ("의 R1–R17 · 권고 기본값", "의 R01–R17 · 권고 기본값"),
    ("# R1 봉인 전 세분 문턱", "# R02 봉인 전 세분 문턱"),
    ("# R1 세분 최대 회수", "# R02 세분 최대 회수"),
    ("# R2 검출 허용", "# R01 검출 허용"),
    ("# R6 자유표면 맞춤", "# R06 자유표면 맞춤"),
    ("# R6 벽 두름 분율", "# R06 벽 두름 분율"),
    ("# R1 — 봉인 전 세분", "# R02 — 봉인 전 세분"),
    ("# R1 — 칸 포괄", "# R02 — 칸 포괄"),
    ("# R1 · R3 — 연결 성분", "# R03 — 연결 성분"),
    ("# R2 — B 의 검출 한계", "# R01 — B 의 검출 한계"),
    ("# R3 — u_DEM = 같은 시험", "# R04 — u_DEM = 같은 시험"),
    ("# R3 — T2 정상 상태", "# R04 — T2 정상 상태"),
    ("# R3 — 곡선 · 재시도", "# R04 — 곡선 · 재시도"),
    ("# R5 — 중심 곡선", "# R05 — 중심 곡선"),
    ("# R6 — T2 각은", "# R06 — T2 각은"),
    ("# R7 — 넘기는 것", "# R07 — 넘기는 것"),
    ("# R8 — S3a", "# R08 — S3a"),
    ("# R9 — 예측", "# R09 — 예측"),
    ("# R4 — u_exp", "# R14 — u_exp"),
]
for a, b in pairs:
    n = s.count(a)
    assert n == 1, (a, n)
    s = s.replace(a, b)
open(p, 'w', encoding='utf-8').write(s)
print('ok', len(pairs))
